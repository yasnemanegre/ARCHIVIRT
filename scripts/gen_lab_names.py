#!/usr/bin/env python3
"""ARCHIVIRT — generate name-resolution blocks for the lab from the Ansible inventory.

The inventory (ansible/inventory/hosts.ini) is the single source of truth for
VM logical names and management IPs. This script prints either:
  --ssh    a ~/.ssh/config block (Host <name> / HostName <ip> / User / IdentityFile)
  --hosts  an /etc/hosts block for the HOST only (not pushed into the VMs, to
           keep network segmentation unchanged)
Both blocks are delimited by markers so they can be replaced idempotently.

Usage:
  python3 scripts/gen_lab_names.py --ssh   > /tmp/archivirt_ssh_block
  python3 scripts/gen_lab_names.py --hosts > /tmp/archivirt_hosts_block
"""
import argparse
import configparser
import os
import sys

BEGIN = "# >>> BEGIN ARCHIVIRT HOSTS (generated by scripts/gen_lab_names.py) >>>"
END = "# <<< END ARCHIVIRT HOSTS <<<"


def read_inventory(path):
    hosts = {}
    group = None
    with open(path) as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith(("#", ";")):
                continue
            if line.startswith("["):
                group = line.strip("[]")
                continue
            if group is None or ":" in group:  # skip [all:vars] etc.
                continue
            fields = line.split()
            name, attrs = fields[0], dict(f.split("=", 1) for f in fields[1:] if "=" in f)
            if "ansible_host" in attrs:
                hosts[name] = attrs
    return hosts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inventory", default=os.path.join(os.path.dirname(__file__), "..", "ansible", "inventory", "hosts.ini"))
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--ssh", action="store_true")
    mode.add_argument("--hosts", action="store_true")
    args = ap.parse_args()

    hosts = read_inventory(args.inventory)
    if not hosts:
        sys.exit("no host with ansible_host found in inventory")

    print(BEGIN)
    for name, attrs in sorted(hosts.items()):
        ip = attrs["ansible_host"]
        if args.hosts:
            print(f"{ip:<15} {name}")
        else:
            print(f"Host {name}")
            print(f"    HostName {ip}")
            print(f"    User {attrs.get('ansible_user', 'ubuntu')}")
            if "ansible_ssh_private_key_file" in attrs:
                print(f"    IdentityFile {attrs['ansible_ssh_private_key_file']}")
            print("    IdentitiesOnly yes")
            # Lab VMs are rebuilt often (new host keys): same policy as the
            # existing IP-pattern block of this file.
            print("    StrictHostKeyChecking no")
            print("    UserKnownHostsFile /dev/null")
            print("    LogLevel ERROR")
    print(END)


if __name__ == "__main__":
    main()
